import { writeFileSync } from "node:fs";
import { PHOTOS, PHOTO_CATEGORIES, type Photo } from "../../src/lib/photography/catalog";
import { PICKS } from "./picks";
import { readCandidates } from "./unsplash";

const OUT = new URL("../../src/lib/photography/photos.ts", import.meta.url);

type Metadata = Pick<Photo, "photographer" | "width" | "height">;

function main() {
  const metadata = new Map<string, Metadata>();
  for (const p of PHOTOS) metadata.set(p.id, p);
  for (const c of readCandidates()) metadata.set(c.id, c);

  const seen = new Map<string, string>();
  const photos: Photo[] = [];
  for (const category of PHOTO_CATEGORIES) {
    for (const pick of PICKS[category]) {
      const prior = seen.get(pick.id);
      if (prior) throw new Error(`${pick.id} picked for both ${prior} and ${category}`);
      seen.set(pick.id, category);
      const meta = metadata.get(pick.id);
      if (!meta) throw new Error(`${pick.id} has no scraped metadata; rerun scrape.ts ${category}`);
      photos.push({
        id: pick.id,
        url: `https://images.unsplash.com/${pick.id}`,
        category,
        alt: pick.alt,
        photographer: meta.photographer.replace(/\s+/g, " ").trim(),
        width: meta.width,
        height: meta.height,
        tone: pick.tone,
      });
    }
  }

  const body = photos.map((p) => `  ${JSON.stringify(p)},`).join("\n");
  writeFileSync(
    OUT,
    `// Generated by scripts/photos/emit.ts from scripts/photos/picks.ts. Do not edit by hand.\n` +
      `import type { Photo } from "./catalog";\n\nexport const PHOTOS: readonly Photo[] = [\n${body}\n];\n`,
  );
  const counts = PHOTO_CATEGORIES.map((c) => `${c}=${PICKS[c].length}`).join(" ");
  console.log(`wrote ${photos.length} photos\n${counts}`);
}

main();
